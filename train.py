#!/usr/bin/env python3
"""python train.py dataset.bin [epochs]  ->  weights.h
dataset.bin: подряд записи [144*256 байт яркости, построчно][8 байт uint64 label, little-endian]
Зависимость: только numpy."""
import sys
import numpy as np

W, H, B = 144, 256, 8
GW, GH = W // B, H // B
NIN, NHID = GW * GH, 32          # NHID больше = умнее, но больше флеша
REC = W * H + 8


def load(path):
    raw = np.fromfile(path, dtype=np.uint8)
    n = raw.size // REC
    raw = raw[:n * REC].reshape(n, REC)
    img = raw[:, :W * H].reshape(n, GH, B, GW, B)
    x = (img.sum((2, 4), dtype=np.uint32) // (B * B)).reshape(n, NIN)  # как в C
    x = x.astype(np.float32) / 255
    lab = np.ascontiguousarray(raw[:, W * H:]).view('<u8').reshape(n)
    y = ((lab[:, None] >> np.arange(64, dtype=np.uint64)) & np.uint64(1)).astype(np.float32)
    return x, y


def forward(P, x):
    z1 = x @ P[0].T + P[1]
    h = np.maximum(z1, 0)
    return z1, h, h @ P[2].T + P[3]


def train(x, y, epochs):
    rng = np.random.default_rng(0)
    f32 = np.float32
    P = [rng.standard_normal((NHID, NIN)).astype(f32) * f32(np.sqrt(2 / NIN)), np.zeros(NHID, f32),
         rng.standard_normal((64, NHID)).astype(f32) * f32(np.sqrt(1 / NHID)), np.zeros(64, f32)]
    m = [np.zeros_like(p) for p in P]
    v = [np.zeros_like(p) for p in P]
    n, bs, lr, t = len(x), min(64, len(x)), 1e-3, 0
    for ep in range(epochs):
        idx = rng.permutation(n)
        for s in range(0, n, bs):
            b = idx[s:s + bs]
            xb, yb = x[b], y[b]
            z1, h, z2 = forward(P, xb)
            dz2 = (1 / (1 + np.exp(-np.clip(z2, -30, 30))) - yb) / len(b)
            dz1 = (dz2 @ P[2]) * (z1 > 0)
            G = [dz1.T @ xb, dz1.sum(0), dz2.T @ h, dz2.sum(0)]
            t += 1
            for i in range(4):
                m[i] = 0.9 * m[i] + 0.1 * G[i]
                v[i] = 0.999 * v[i] + 0.001 * G[i] ** 2
                P[i] -= lr * (m[i] / (1 - 0.9 ** t)) / (np.sqrt(v[i] / (1 - 0.999 ** t)) + 1e-8)
        if ep % max(1, epochs // 10) == 0 or ep == epochs - 1:
            ok = ((forward(P, x)[2] > 0) == (y > 0.5)).all(1).mean()
            print(f"epoch {ep:4d}  точных совпадений 64 бит: {ok * 100:.1f}%")
    return P


def dump(P, path="weights.h"):
    with open(path, "w") as f:
        f.write(f"/* generated by train.py */\n#define NN_HID {NHID}\n")
        for name, a in zip(["nn_w1", "nn_b1", "nn_w2", "nn_b2"], P):
            a = a.ravel()
            f.write(f"static const float {name}[{a.size}] = {{\n")
            for i in range(0, a.size, 8):
                f.write("  " + ", ".join("%.9ef" % u for u in a[i:i + 8]) + ",\n")
            f.write("};\n")


if __name__ == "__main__":
    x, y = load(sys.argv[1])
    print(f"{len(x)} примеров")
    dump(train(x, y, int(sys.argv[2]) if len(sys.argv) > 2 else 300))
    print("weights.h готов")
